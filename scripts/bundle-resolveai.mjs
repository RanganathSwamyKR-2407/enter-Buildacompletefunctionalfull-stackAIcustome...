// =====================================================================
// Bundle the resolveai backend function into a single self-contained
// index.ts for deployment (the deploy tool only uploads direct files of
// the function folder, so shared modules must be inlined).
//
// Run: node scripts/bundle-resolveai.mjs
// =====================================================================
import fs from "node:fs";
import path from "node:path";

const ROOT = "supabase/functions/resolveai";
const INDEX = path.join(ROOT, "index.ts");
const ROUTER = path.join(ROOT, "router.ts");
const SHARED = path.join(ROOT, "_shared");
const NL = String.fromCharCode(10);

function stripImports(src) {
  const esmImports = [];
  const out = [];
  const lines = src.split(NL);
  for (let i = 0; i < lines.length; i++) {
    const t = lines[i].trim();
    if (!t.startsWith("import ")) {
      out.push(lines[i]);
      continue;
    }
    // Collect the whole import statement (may span several lines).
    let block = lines[i];
    let j = i;
    const hasFrom = / from ["']/.test(block);
    if (!hasFrom) {
      while (j + 1 < lines.length) {
        j++;
        block += " " + lines[j].trim();
        if (/ from ["']/.test(block) && /;?\s*$/.test(lines[j])) break;
      }
    }
    const m = block.match(/from\s+["']([^"']+)["']/);
    if (m && m[1].startsWith("http")) esmImports.push(block);
    i = j;
  }
  return { src: out.join(NL), esmImports };
}

function collectTs(dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...collectTs(p));
    else if (entry.name.endsWith(".ts")) files.push(p);
  }
  return files;
}

const esmSet = new Set();
const bodyParts = [];
for (const file of collectTs(SHARED).sort()) {
  const src = fs.readFileSync(file, "utf8");
  const { src: stripped, esmImports } = stripImports(src);
  for (const imp of esmImports) esmSet.add(imp);
  bodyParts.push(`// --- ${path.relative(ROOT, file)} ---` + NL + stripped);
}

const routerSrc = fs.readFileSync(ROUTER, "utf8");
const { src: routerStripped } = stripImports(routerSrc);

const header = [
  "// AUTO-GENERATED by scripts/bundle-resolveai.mjs - do not edit by hand.",
  "// Source of truth: supabase/functions/resolveai/ (index.ts + _shared/).",
  ...esmSet,
  "",
].join(NL);

const bundle = [header, ...bodyParts, "", "// --- router ---", routerStripped].join(NL);
fs.writeFileSync(INDEX, bundle + NL);
console.log(`Bundled resolveai function -> ${bundle.length} chars, ${esmSet.size} remote import(s).`);
